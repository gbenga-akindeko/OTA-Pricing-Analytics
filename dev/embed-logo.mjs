// Embeds the Finchglow logo into apps-script/Logo.html as a data URI, so the
// portal shows it without hosting the file anywhere.
//   1. Save the logo as assets/finchglow-logo.png (or .svg / .jpg)
//   2. npm run embed-logo
//   3. npm run push   (or paste Logo.html into the Apps Script editor)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const types = { '.png': 'image/png', '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };
const file = Object.keys(types).map((ext) => path.join(root, 'assets', 'finchglow-logo' + ext)).find((f) => fs.existsSync(f));
if (!file) {
  console.error('No logo found. Save it as assets/finchglow-logo.png (or .svg, .jpg, .webp) and run again.');
  process.exit(1);
}
const bytes = fs.readFileSync(file);
if (bytes.length > 400 * 1024) {
  console.error(`The logo is ${Math.round(bytes.length / 1024)} KB. Please use a version under 400 KB (around 600px wide is plenty).`);
  process.exit(1);
}
const uri = `data:${types[path.extname(file).toLowerCase()]};base64,${bytes.toString('base64')}`;
fs.writeFileSync(path.join(root, 'apps-script', 'Logo.html'), `<script>
  // Generated by \`npm run embed-logo\` from ${path.relative(root, file)}. Do not edit by hand.
  window.EMBEDDED_LOGO = '${uri}';
</script>
`);
console.log(`Embedded ${path.relative(root, file)} (${Math.round(bytes.length / 1024)} KB) into apps-script/Logo.html`);
