// Builds a 3-file copy of the portal in dist/ for pasting into the Apps Script editor:
//   dist/Code.gs           all server code in one file
//   dist/Index.html        the page with styles, logo and client code inlined
//   dist/appsscript.json   the manifest
//   npm run bundle
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'apps-script');

// Server files in a readable order. Apps Script loads them all into one scope, so order does not change behaviour.
const ORDER = ['Config.js', 'Db.js', 'Auth.js', 'Rates.js', 'Analytics.js', 'Email.js', 'Admin.js', 'Setup.js', 'Code.js'];

export function buildBundle() {
  const jsFiles = fs.readdirSync(src).filter((f) => f.endsWith('.js'));
  const missing = jsFiles.filter((f) => !ORDER.includes(f));
  if (missing.length) throw new Error('Add these files to ORDER in dev/bundle.mjs: ' + missing.join(', '));
  const code = '// Finchglow Holdings Finance One-Stop Portal. Generated by `npm run bundle` from apps-script/. Do not edit here.\n\n' +
    ORDER.map((f) => `// ===== ${f} =====\n` + fs.readFileSync(path.join(src, f), 'utf8').trim() + '\n').join('\n');
  const index = fs.readFileSync(path.join(src, 'Index.html'), 'utf8')
    .replace(/<\?!=\s*include\('(\w+)'\);?\s*\?>/g, (m, name) => fs.readFileSync(path.join(src, name + '.html'), 'utf8').trim());
  if (/<\?/.test(index)) throw new Error('Index.html still contains a scriptlet after inlining');
  return {
    'Code.gs': code,
    'Index.html': index,
    'appsscript.json': fs.readFileSync(path.join(src, 'appsscript.json'), 'utf8')
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'dist');
  fs.mkdirSync(out, { recursive: true });
  for (const [name, content] of Object.entries(buildBundle())) {
    fs.writeFileSync(path.join(out, name), content);
    console.log(`dist/${name}  ${Math.round(Buffer.byteLength(content) / 1024)} KB`);
  }
}
